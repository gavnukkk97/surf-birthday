BBOX = (36.2, 54.8, 38.95, 56.5)  # lon1, lat1, lon2, lat2


def geocode(query):
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode({
        "format": "jsonv2", "limit": "3", "accept-language": "ru",
        "countrycodes": "ru", "q": query,
        "viewbox": f"{BBOX[0]},{BBOX[1]},{BBOX[2]},{BBOX[3]}", "bounded": "1",
    })
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    try:
        with urllib.request.urlopen(req, timeout=25) as r:
            return json.load(r)
    except Exception as e:
        return {"error": str(e)}


def in_bbox(lat, lon):
    return BBOX[1] <= lat <= BBOX[3] and BBOX[0] <= lon <= BBOX[2]


def localized(res):
    bb = [float(x) for x in res.get("boundingbox", [])]
    if len(bb) != 4:
        return False
    return (bb[2] - bb[0]) < 0.05 and (bb[3] - bb[1]) < 0.05  # <~5.5km box


